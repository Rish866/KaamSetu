-- 202611260001 Pan-India locations.
-- Replaces the Mumbai/Thane/Navi Mumbai/Pune-only catalogue with a structured India-wide one:
--   state/UT (36) -> district (737) -> city / locality -> PIN code (19,300), plus "entire state" places.
-- Existing location rows keep their ids (jobs and candidate profiles point at them) and are linked to their district.
-- Adds: search_locations() for type-ahead, job_search() with multi-place / state / PIN-prefix / remote filters,
-- discover_candidates() with the same location filters, and a hierarchical location score.
-- job_feed() and search_candidates() are unchanged so the previous website keeps working until it is redeployed.
-- Data: Department of Posts, Government of India, "All India Pincode Directory" (data.gov.in), Government Open Data
-- License - India. Generated by scripts/geo/build-india-locations.py; see docs/ATTRIBUTION.md.

------------------------------------------------------------------------------
-- 1. States/UTs and districts
------------------------------------------------------------------------------
create table public.states (
  code text primary key check (code ~ '^[A-Z]{2}$'),
  name text not null unique,
  kind text not null check (kind in ('state', 'union_territory'))
);
create table public.districts (
  id uuid primary key default gen_random_uuid(),
  state_code text not null references public.states(code),
  name text not null,
  unique (state_code, name)
);
alter table public.states enable row level security;
alter table public.districts enable row level security;
create policy states_read on public.states for select to anon, authenticated using (true);
create policy districts_read on public.districts for select to anon, authenticated using (true);
revoke all on public.states, public.districts from anon, authenticated, service_role;
grant select on public.states, public.districts to anon, authenticated;

create table private.pin_import (pincode text primary key, state_code text not null, district text not null,
  city text not null, locality text, aliases text);
revoke all on private.pin_import from public, anon, authenticated, service_role;

------------------------------------------------------------------------------
-- 2. Location hierarchy on the existing table
------------------------------------------------------------------------------
alter table public.locations drop constraint if exists locations_city_locality_key;
alter table public.locations
  add column kind text not null default 'city' check (kind in ('state', 'district', 'city', 'locality', 'pin')),
  add column state_code text references public.states(code),
  add column district_id uuid references public.districts(id),
  add column district text,
  add column pincode text check (pincode ~ '^[1-9][0-9]{5}$'),
  add column aliases text,
  add column search_text text generated always as (
    lower(coalesce(locality, '') || ' ' || city || ' ' || coalesce(district, '') || ' ' || coalesce(pincode, '') || ' ' || coalesce(aliases, ''))) stored;
