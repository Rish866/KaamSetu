#!/usr/bin/env python3
"""Returns the latest definition of a SQL function from supabase/migrations (for generating new migrations that change it).
   python3 scripts/sqlgen/extract.py public.apply_to_job"""
import glob, os, re, sys
BEFORE = '202611270001'  # migrations generated by build-enhancements.py are not sources
def latest(name, before=BEFORE):
    best = None
    for f in sorted(glob.glob('supabase/migrations/*.sql')):
        if os.path.basename(f) >= before: continue
        s = open(f).read()
        for m in re.finditer(r'create (?:or replace )?function ' + re.escape(name) + r'\(', s):
            end = s.index('$$;', s.index('$$', m.start()) + 2) + 3
            best = (f, s[m.start():end])
    if not best: raise SystemExit('not found ' + name)
    return best
if __name__ == '__main__':
    f, body = latest(sys.argv[1]); print('-- from', f); print(body)
